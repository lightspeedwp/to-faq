/**
 * Class Faq
 *
 * Makes the Yoast FAQ block collapsible. The accordion assets only load on
 * pages that render the block. The FAQ template part area itself is
 * registered by the Tour Operator core plugin.
 *
 * @package lsx\to_faq
 */
class Faq {

	/**
	 * Asset handle. It matches the handle used by Tour Operator core, so the
	 * accordion script is only enqueued once if both plugins provide it.
	 *
	 * @var string
	 */
	const HANDLE = 'lsx-to-faq-accordion';

	/**
	 * The block the accordion enhances.
	 *
	 * @var string
	 */
	const BLOCK = 'yoast/faq-block';

	/**
	 * Tour Operator FAQ constructor.
	 */
	public function __construct() {
		add_action( 'init', array( $this, 'load_textdomain' ) );
		add_action( 'init', array( $this, 'enqueue_accordion_style' ) );
		add_filter( 'render_block_' . self::BLOCK, array( $this, 'enqueue_accordion_script' ), 10, 1 );
	}

	/**
	 * Load the plugin text domain for translation.
	 */
	public function load_textdomain() {
		load_plugin_textdomain( 'to-faq', false, dirname( plugin_basename( LSX_TO_FAQ_CORE ) ) . '/languages' );
	}

	/**
	 * Attach the accordion stylesheet to the Yoast FAQ block, so it only
	 * loads when the block is on the page.
	 */
	public function enqueue_accordion_style() {
		$asset = $this->get_asset( 'css/faq-accordion' );

		wp_enqueue_block_style(
			self::BLOCK,
			array(
				'handle' => self::HANDLE,
				'src'    => LSX_TO_FAQ_URL . 'build/css/faq-accordion.css',
				'path'   => LSX_TO_FAQ_PATH . 'build/css/faq-accordion.css',
				'ver'    => $asset['version'],
			)
		);
	}

	/**
	 * Enqueue the accordion script when a Yoast FAQ block is rendered.
	 *
	 * @param string $block_content The block content.
	 * @return string The unchanged block content.
	 */
	public function enqueue_accordion_script( $block_content ) {
		if ( ! wp_script_is( self::HANDLE, 'enqueued' ) ) {
			$asset = $this->get_asset( 'js/faq-accordion' );

			wp_enqueue_script(
				self::HANDLE,
				LSX_TO_FAQ_URL . 'build/js/faq-accordion.js',
				$asset['dependencies'],
				$asset['version'],
				array(
					'in_footer' => true,
					'strategy'  => 'defer',
				)
			);
		}

		return $block_content;
	}

	/**
	 * Read the dependencies and version generated by wp-scripts for an entry.
	 *
	 * @param string $entry The webpack entry name, relative to build/.
	 * @return array{dependencies: string[], version: string}
	 */
	private function get_asset( $entry ) {
		$asset_file = LSX_TO_FAQ_PATH . 'build/' . $entry . '.asset.php';
		$asset      = file_exists( $asset_file ) ? require $asset_file : array();

		return array(
			'dependencies' => isset( $asset['dependencies'] ) ? $asset['dependencies'] : array(),
			'version'      => isset( $asset['version'] ) ? $asset['version'] : LSX_TO_FAQ_VER,
		);
	}
}
